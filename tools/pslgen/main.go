// pslgen turns the Public Suffix List (https://publicsuffix.org, MPL-2.0)
// into extension/src/psl.js, the rules the browser extension uses to tell
// which sites belong together (example.co.uk and shop.example.co.uk do,
// a.github.io and b.github.io do not). Download the list and run:
//
//	go run ./tools/pslgen public_suffix_list.dat
package main

import (
	"bufio"
	"fmt"
	"os"
	"sort"
	"strings"

	"golang.org/x/net/idna"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: pslgen public_suffix_list.dat")
		os.Exit(2)
	}
	if err := run(os.Args[1]); err != nil {
		fmt.Fprintln(os.Stderr, "pslgen:", err)
		os.Exit(1)
	}
}

func run(src string) error {
	f, err := os.Open(src) // #nosec G304 G703 -- a file named on the command line of this developer tool
	if err != nil {
		return err
	}
	defer f.Close()
	seen := map[string]bool{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "//") {
			continue
		}
		rule := strings.Fields(line)[0]
		prefix := ""
		if strings.HasPrefix(rule, "!") {
			prefix, rule = "!", rule[1:]
		}
		labels := strings.Split(rule, ".")
		for i, l := range labels {
			if l == "*" {
				continue
			}
			a, err := idna.Lookup.ToASCII(l)
			if err != nil {
				a, err = idna.Punycode.ToASCII(l)
				if err != nil {
					return fmt.Errorf("rule %q: %w", line, err)
				}
			}
			labels[i] = strings.ToLower(a)
		}
		seen[prefix+strings.Join(labels, ".")] = true
	}
	if err := sc.Err(); err != nil {
		return err
	}
	rules := make([]string, 0, len(seen))
	for r := range seen {
		rules = append(rules, r)
	}
	sort.Strings(rules)
	var b strings.Builder
	b.WriteString("// The Public Suffix List (https://publicsuffix.org), Mozilla Public License 2.0:\n")
	b.WriteString("// https://mozilla.org/MPL/2.0/. Generated by tools/pslgen; do not edit.\n")
	b.WriteString("export const RULES = \"" + strings.Join(rules, ",") + "\";\n")
	if err := os.WriteFile("extension/src/psl-rules.js", []byte(b.String()), 0o600); err != nil {
		return err
	}
	fmt.Printf("extension/src/psl-rules.js: %d rules\n", len(rules))
	return nil
}
